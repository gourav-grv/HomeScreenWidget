#!/usr/bin/env node
/*
 * Android: generates one widget provider per widget type (after_prepare, idempotent).
 *  - java:     io.homescreenwidget.plugin.HswWidget_<key> extends GenericWidgetProvider
 *  - manifest: one <receiver> per type, labelled with the type's label
 *  - values:   res/values/hsw_widget_types.xml (labels)
 */
'use strict';

var fs = require('fs');
var path = require('path');
var types = require('../widget_types');

var START = '<!-- HSW-WIDGET-TYPES-START -->';
var END = '<!-- HSW-WIDGET-TYPES-END -->';

function firstExisting(paths) {
    for (var i = 0; i < paths.length; i++) if (fs.existsSync(paths[i])) return paths[i];
    return null;
}

module.exports = function (context) {
    var root = context.opts.projectRoot;
    var appMain = path.join(root, 'platforms', 'android', 'app', 'src', 'main');
    if (!fs.existsSync(appMain)) return;

    var list = types.readTypes([
        path.join(root, 'config.xml'),
        path.join(appMain, 'res', 'xml', 'config.xml')
    ]);

    // 1. Java subclasses
    var javaDir = firstExisting([path.join(appMain, 'java', 'io', 'homescreenwidget', 'plugin')]) ||
        path.join(appMain, 'java', 'io', 'homescreenwidget', 'plugin');
    if (!fs.existsSync(javaDir)) fs.mkdirSync(javaDir, { recursive: true });
    fs.readdirSync(javaDir).forEach(function (f) {
        if (/^HswWidget_.*\.java$/.test(f)) fs.unlinkSync(path.join(javaDir, f));
    });
    list.forEach(function (t) {
        var cls = 'HswWidget_' + t.key;
        fs.writeFileSync(path.join(javaDir, cls + '.java'),
            'package io.homescreenwidget.plugin;\n\n' +
            '/** Generated by cordova-plugin-homescreen-widget for widget type "' + t.key + '". */\n' +
            'public class ' + cls + ' extends GenericWidgetProvider {\n' +
            '    @Override\n' +
            '    protected String widgetKey() { return "' + t.key + '"; }\n' +
            '}\n');
    });

    // 2. Labels
    var valuesDir = path.join(appMain, 'res', 'values');
    if (!fs.existsSync(valuesDir)) fs.mkdirSync(valuesDir, { recursive: true });
    var strings = '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n';
    list.forEach(function (t) {
        if (t.label) strings += '    <string name="hsw_label_' + t.key + '">' + types.escapeXml(t.label) + '</string>\n';
    });
    strings += '</resources>\n';
    fs.writeFileSync(path.join(valuesDir, 'hsw_widget_types.xml'), strings);

    // 3. Manifest receivers
    var manifestPath = path.join(appMain, 'AndroidManifest.xml');
    var manifest = fs.readFileSync(manifestPath, 'utf8');
    var startIdx = manifest.indexOf(START);
    var endIdx = manifest.indexOf(END);
    if (startIdx !== -1 && endIdx !== -1) {
        manifest = manifest.slice(0, startIdx) + manifest.slice(endIdx + END.length);
    }
    var block = START + '\n';
    list.forEach(function (t) {
        block +=
            '        <receiver android:name="io.homescreenwidget.plugin.HswWidget_' + t.key + '"\n' +
            '                  android:exported="true"\n' +
            '                  android:label="' + (t.label ? '@string/hsw_label_' + t.key : '@string/app_name') + '">\n' +
            '            <intent-filter>\n' +
            '                <action android:name="android.appwidget.action.APPWIDGET_UPDATE" />\n' +
            '            </intent-filter>\n' +
            '            <meta-data android:name="android.appwidget.provider" android:resource="@xml/hsw_widget_info" />\n' +
            '        </receiver>\n';
    });
    block += '        ' + END;
    var appClose = manifest.lastIndexOf('</application>');
    if (appClose === -1) {
        console.warn('[HomeScreenWidget] </application> not found in AndroidManifest.xml');
        return;
    }
    manifest = manifest.slice(0, appClose) + '        ' + block + '\n    ' + manifest.slice(appClose);
    fs.writeFileSync(manifestPath, manifest);

    console.log('[HomeScreenWidget] Android widget types: ' + list.map(function (t) { return t.key + (t.label ? ' (' + t.label + ')' : ''); }).join(', '));
};
